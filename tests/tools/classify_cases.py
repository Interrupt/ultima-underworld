#!/usr/bin/env python3
"""Work out which unit-test cases pass without real game data.

Run against a build directory configured with UW_TEST_DATA_DIR pointing at the synthetic tree
(tests/tools/make_synthetic_data.py). Every Unity case of every test executable is run on its own;
the ones that pass are data-free and are written to tests/unit-cases.txt as

    <ctest name> *                  every case passes (also used for non-Unity tests)
    <ctest name> case_a,case_b      only these cases pass; the rest need the real data

CMake reads that file to create a `<name>.unit` test per executable. Usage:

    classify_cases.py BUILD_DIR [OUTPUT_FILE]
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path


def run(command, cwd, env_extra):
    env = dict(os.environ, **env_extra)
    return subprocess.run(command, cwd=cwd, env=env, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                          text=True, errors="replace", timeout=300)


def classify(test):
    command = test["command"]
    cwd = next((p["value"] for p in test.get("properties", []) if p["name"] == "WORKING_DIRECTORY"),
               None)
    listing = run(command, cwd, {"UW_TEST_LIST": "1"})
    cases = [l[5:].strip() for l in listing.stdout.splitlines() if l.startswith("CASE ")]
    if not cases:  # not a Unity executable: all-or-nothing
        return test["name"], "*" if run(command, cwd, {}).returncode == 0 else None
    passing = [c for c in cases if run(command, cwd, {"UW_TEST_CASES": c}).returncode == 0]
    if len(passing) == len(cases):
        return test["name"], "*"
    return test["name"], ",".join(passing) if passing else None


def main():
    build = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else \
        Path(__file__).resolve().parent.parent / "unit-cases.txt"
    info = json.loads(subprocess.check_output(
        ["ctest", "--test-dir", str(build), "--show-only=json-v1"], text=True))
    tests = [t for t in info["tests"] if not t["name"].endswith(".unit")]
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        results = sorted(pool.map(classify, tests))
    lines = [
        "# Unit-test cases that pass without real game data, generated by tools/classify_cases.py",
        "# against the synthetic data tree. Format: <ctest name> * | <ctest name> case,case,...",
        "# Everything not listed needs the real data and runs as an integration test.",
    ]
    lines += [f"{name} {cases}" for name, cases in results if cases]
    output.write_text("\n".join(lines) + "\n")
    total = len(results)
    full = sum(1 for _, c in results if c == "*")
    part = sum(1 for _, c in results if c and c != "*")
    print(f"{full} fully data-free, {part} partly, {total - full - part} integration-only "
          f"(of {total}); wrote {output}")


if __name__ == "__main__":
    main()
